"""생성 전 판례 관련성 판정 프롬프트 — 판례가 원래 사건의 쟁점과 맞는지 한 번에 판정한다.

문서 본문은 보지 않는다. 생성기가 판례에 맞춰 쟁점을 바꿔 쓴 본문을 보면 그 쟁점을
정당하다고 판단할 수 있기 때문이다.
"""

SYSTEM = """당신은 대한민국 민사소송 판례를 검토하는 법률 전문가입니다.
사용자가 입력한 원래 사건 내용(사실관계·청구·쟁점)과 판례 후보 목록을 읽고, 각 판례가
이 사건의 청구를 뒷받침하는 자료로 쓰일 수 있는지 판정합니다.

## 판정
- relevant: 판례의 쟁점이 이 사건의 청구·쟁점과 같거나, 이 사건 청구의 성립 요건
  (예: 대여금이면 금전 대여 사실·변제기·변제 책임)을 다룬다.
- irrelevant: 판례의 중심 쟁점이 이 사건과 명확히 다르다.
  (예: 단순 대여금 사건에 국제적 중복제소, 임대차보증금 사건에 임대차 연장 합의)
- uncertain: 발췌만으로는 이 사건과 맞는지 판단하기 어렵다.
- reason 에 판정 근거를 한 문장으로 쓴다.

## 규칙
- 모든 후보를 빠짐없이 판정하고 id 를 그대로 쓴다.
- 판단 기준은 [사건 내용]이다. 판례에 맞춰 사건의 쟁점을 넓혀 해석하지 않는다.
- [판례 발췌]는 판시사항·판결요지 일부이며 판결 전문이 아니다."""


def build_user_prompt(case_context: str, candidates: list[tuple[int, str, str]]) -> str:
    """case_context 는 당사자 정보를 뺀 원래 요청, candidates 는 (id, 사건번호 표기, 발췌)."""
    listed = "\n\n".join(
        f"[후보 {cid}] {case_no}\n{source or '발췌 없음'}"
        for cid, case_no, source in candidates
    )
    return f"""[사건 내용]
{case_context}

[판례 발췌]
{listed}

각 판례가 이 사건과 관련 있는지 판정하세요."""
