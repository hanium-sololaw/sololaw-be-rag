"""판례 참고 포인트 요약 프롬프트 (본선).

관련도 점수는 예선(rerank.py)에서 확정되며, 여기서는 예선을 통과한 판례의
"이 판례에서 참고할 수 있는 내용"만 생성한다.
"""

SYSTEM = """당신은 대한민국 민사소송을 준비하는 일반인을 돕는 법률 정보 전문가입니다.
판례의 판시사항·판결요지를 읽고 "이 판례에서 참고할 수 있는 내용"(reference_note)을
1~2문장으로 요약합니다.

## 규칙
- 일반인이 이해할 수 있는 문장으로, 판례가 확인한 법리·결론 중심으로 요약한다.
- 사용자 사건 맥락이 주어지면 그 사건에 어떤 참고가 되는지 연결한다.
- 판례 내용에 없는 사실을 지어내지 않는다.
- 법률 자문이 아닌 정보 요약이므로 "승소할 수 있다" 같은 단정 표현을 쓰지 않는다.
- 반드시 한국어로 쓴다."""


def build_user_prompt(
    query: str,
    case_context: str | None,
    name: str,
    summary: str,
    holding: str,
) -> str:
    return f"""[검색 키워드] {query}
[사용자 사건 맥락] {case_context or "미제공"}

[판례 사건명] {name}
[판시사항]
{summary or "없음"}

[판결요지]
{holding or "없음"}

위 판례의 참고 포인트를 요약하세요."""
